CREATE TABLE IF NOT EXISTS user_account (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(64) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, name VARCHAR(80) NOT NULL, role VARCHAR(16) NOT NULL
);
CREATE TABLE IF NOT EXISTS venue (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, location VARCHAR(160) NOT NULL,
 capacity INT NOT NULL, equipment VARCHAR(500) NOT NULL, open_time VARCHAR(5) NOT NULL,
 close_time VARCHAR(5) NOT NULL, hourly_rate DECIMAL(10,2) NOT NULL, category VARCHAR(40) NOT NULL,
 description VARCHAR(1000) NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS booking (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, applicant_id BIGINT NOT NULL, venue_id BIGINT NOT NULL,
 start_time TIMESTAMP NOT NULL, end_time TIMESTAMP NOT NULL, attendees INT NOT NULL,
 purpose VARCHAR(500) NOT NULL, status VARCHAR(24) NOT NULL, reason VARCHAR(500),
 rate_snapshot DECIMAL(10,2), created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL,
 FOREIGN KEY (applicant_id) REFERENCES user_account(id), FOREIGN KEY (venue_id) REFERENCES venue(id),
 INDEX idx_booking_venue_time (venue_id, start_time, end_time)
);
CREATE TABLE IF NOT EXISTS closure (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, venue_id BIGINT NOT NULL, start_time TIMESTAMP NOT NULL,
 end_time TIMESTAMP NOT NULL, reason VARCHAR(500) NOT NULL, created_by BIGINT NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP NOT NULL,
 FOREIGN KEY (venue_id) REFERENCES venue(id)
);
CREATE TABLE IF NOT EXISTS usage_record (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, booking_id BIGINT NOT NULL UNIQUE, actual_start TIMESTAMP NOT NULL,
 actual_end TIMESTAMP NULL, registered_by BIGINT NOT NULL, note VARCHAR(500),
 FOREIGN KEY (booking_id) REFERENCES booking(id)
);
CREATE TABLE IF NOT EXISTS fee_record (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, booking_id BIGINT NOT NULL UNIQUE, hourly_rate DECIMAL(10,2) NOT NULL,
 minutes_used BIGINT NOT NULL, amount DECIMAL(12,2) NOT NULL, paid BOOLEAN NOT NULL DEFAULT FALSE,
 confirmed_by BIGINT NULL, confirmed_at TIMESTAMP NULL, FOREIGN KEY (booking_id) REFERENCES booking(id)
);
CREATE TABLE IF NOT EXISTS audit_log (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, booking_id BIGINT NULL, actor_id BIGINT NOT NULL,
 action VARCHAR(60) NOT NULL, detail VARCHAR(1000) NOT NULL, created_at TIMESTAMP NOT NULL
);
